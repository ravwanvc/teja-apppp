export function LanguageProvider({ children }) {
  const [lang, L] = useState("uz");
  useEffect(() => {
    queueMicrotask(() =>
      L(localStorage.getItem("teja-language") === "ru" ? "ru" : "uz"),
    );
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  function setLang(next) {
    L(next);
    try {
      localStorage.setItem("teja-language", next);
    } catch {}
    document.documentElement.lang = next;
  }
  return (
    <Language.Provider value={{ lang, setLang }}>
      {children}
    </Language.Provider>
  );
}
export function Translated({ children }) {
  const { lang } = useContext(Language);
  return lang === "ru" ? dictionary[children] || (typeof children === "string" && children.includes(" / ") ? children.split(" / ").slice(1).join(" / ") : children) : children;
}
export function useLanguage() {
  return useContext(Language);
}

